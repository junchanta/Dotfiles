-- =============================================================================
-- Keymaps Configuration
-- =============================================================================

local keymap = vim.keymap.set
local opts = { noremap = true, silent = true }

-- -----------------------------------------------------------------------------
-- Leader Key (Must be set before lazy.nvim loads)
-- -----------------------------------------------------------------------------
-- スペースをリーダーキーとして使用（最も一般的）
vim.g.mapleader = " "
vim.g.maplocalleader = " "

-- -----------------------------------------------------------------------------
-- Basic Navigation
-- -----------------------------------------------------------------------------
-- 折り返し時に表示行単位での移動できるようにする
keymap("n", "j", "gj", opts)
keymap("n", "k", "gk", opts)

-- -----------------------------------------------------------------------------
-- Insert Mode Mappings
-- -----------------------------------------------------------------------------
keymap("i", "<C-p>", "<Up>", opts)
keymap("i", "<C-n>", "<Down>", opts)
keymap("i", "<C-b>", "<Left>", opts)
keymap("i", "<C-f>", "<Right>", opts)

-- -----------------------------------------------------------------------------
-- Tabs
-- -----------------------------------------------------------------------------
keymap("n", "te", ":tabedit<CR>", opts)
keymap("n", "<S-Tab>", ":tabprev<CR>", opts)
keymap("n", "<Tab>", ":tabnext<CR>", opts)

-- -----------------------------------------------------------------------------
-- Windows - Split
-- -----------------------------------------------------------------------------
keymap("n", "ss", ":split<CR><C-w>w", opts)
keymap("n", "sv", ":vsplit<CR><C-w>w", opts)

-- -----------------------------------------------------------------------------
-- Windows - Move
-- -----------------------------------------------------------------------------
keymap("n", "<Space>", "<C-w>w", opts)
keymap("n", "s<left>", "<C-w>h", opts)
keymap("n", "s<up>", "<C-w>k", opts)
keymap("n", "s<down>", "<C-w>j", opts)
keymap("n", "s<right>", "<C-w>l", opts)
keymap("n", "sh", "<C-w>h", opts)
keymap("n", "sk", "<C-w>k", opts)
keymap("n", "sj", "<C-w>j", opts)
keymap("n", "sl", "<C-w>l", opts)

-- -----------------------------------------------------------------------------
-- Windows - Resize
-- -----------------------------------------------------------------------------
keymap("n", "<C-w><left>", "<C-w><", opts)
keymap("n", "<C-w><right>", "<C-w>>", opts)
keymap("n", "<C-w><up>", "<C-w>+", opts)
keymap("n", "<C-w><down>", "<C-w>-", opts)

-- -----------------------------------------------------------------------------
-- Search
-- -----------------------------------------------------------------------------
-- ESC連打でハイライト解除
keymap("n", "<Esc><Esc>", ":nohlsearch<CR><Esc>", opts)
